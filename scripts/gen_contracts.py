"""Export Python-owned NER, OCR, and STT schemas, fixtures, and Rust wire structs.

Run with `uv run python scripts/gen_contracts.py`; CI uses `--check`.
Rust types are generated by pinned cargo-typify; semantic conversions remain
in the handwritten Rust adapters. Python exports the authoritative schemas.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import tempfile
from pathlib import Path

from contract_fixtures import fixtures
from elide_core.ner.v1.contract import NerInput, NerOutput
from elide_core.ocr.v1 import OcrInput, OcrOutput
from elide_core.stt.v1 import SttInput, SttOutput

ROOT = Path(__file__).resolve().parents[1]
MODELS = {
    "ner": (NerInput, NerOutput),
    "ocr": (OcrInput, OcrOutput),
    "stt": (SttInput, SttOutput),
}


TYPIFY_VERSION = "0.5.0"


def draft7(value):
    """Translate Pydantic's definitions and tuple keywords for Typify's Draft 7 reader."""
    if isinstance(value, list):
        return [draft7(item) for item in value]
    if not isinstance(value, dict):
        return value
    result = {
        ("definitions" if key == "$defs" else key): draft7(item) for key, item in value.items()
    }
    if "$ref" in result:
        result["$ref"] = result["$ref"].replace("#/$defs/", "#/definitions/")
    if "prefixItems" in result:
        result["items"] = result.pop("prefixItems")
        result["additionalItems"] = False
    if "$schema" in result:
        result["$schema"] = "http://json-schema.org/draft-07/schema#"
    return result


def rust_types(schemas: dict) -> str:
    """Use Typify for code generation; do not maintain a separate Rust emitter."""
    version = subprocess.run(
        ["cargo", "typify", "--version"], text=True, capture_output=True, check=True
    ).stdout.strip()
    if version.split()[-1] != TYPIFY_VERSION:
        raise RuntimeError(f"Install cargo-typify {TYPIFY_VERSION}, found {version}")
    bundle = dict(schemas["request"])
    definitions = {}
    for schema in schemas.values():
        for name, definition in schema.get("$defs", {}).items():
            if name in definitions and definitions[name] != definition:
                raise ValueError(f"conflicting definition: {name}")
            definitions[name] = definition
    output = {
        key: value for key, value in schemas["response"].items() if key not in {"$defs", "$schema"}
    }
    definitions[output["title"]] = output
    bundle["$defs"] = definitions
    with tempfile.TemporaryDirectory() as directory:
        source = Path(directory) / "contract.json"
        source.write_text(json.dumps(draft7(bundle)))
        generated = subprocess.run(
            ["cargo", "typify", str(source), "--no-builder", "--output", "-"],
            text=True,
            capture_output=True,
            check=True,
        )
    # Match the repository's nightly formatting rules, including derive paths.
    formatted = subprocess.run(
        ["rustfmt", "+nightly", "--edition", "2024"],
        input=generated.stdout,
        text=True,
        capture_output=True,
        check=True,
    )
    return (
        "// Generated by scripts/gen_contracts.py using cargo-typify "
        + TYPIFY_VERSION
        + ". Do not edit.\n"
        + formatted.stdout
    )


def service_artifacts(service: str) -> dict[Path, str]:
    request_model, response_model = MODELS[service]
    contract = ROOT / f"contracts/{service}/v1"
    rust = ROOT / f"crates/adapter/elide-bentoml/src/{service}/wire.rs"
    schemas = {
        "request": request_model.model_json_schema(by_alias=True, mode="validation"),
        "response": response_model.model_json_schema(by_alias=True, mode="serialization"),
    }
    result = {}
    for name, schema in schemas.items():
        schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
        result[contract / f"{name}.schema.json"] = (
            json.dumps(schema, indent=2, ensure_ascii=False) + "\n"
        )
    result[rust] = rust_types(schemas)
    result[contract / "fixtures.json"] = (
        json.dumps(fixtures(service), indent=2, ensure_ascii=False) + "\n"
    )
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    artifacts = {}
    for service in MODELS:
        artifacts.update(service_artifacts(service))
    for path, content in artifacts.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        parser.exit(
            1,
            "Stale contract artifacts; run scripts/gen_contracts.py:\n" + "\n".join(stale) + "\n",
        )


if __name__ == "__main__":
    main()
